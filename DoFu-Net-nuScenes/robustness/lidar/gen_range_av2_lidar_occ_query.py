"""
Generate fixed yaw-sector LiDAR occlusion range images for AV2S test queries only.

This script does NOT touch training data or database range images. It creates four
query-only range folders by default:
    occ_030_seed2026, occ_060_seed2026, occ_090_seed2026, occ_120_seed2026

Each query frame uses a fixed random center yaw saved in CSV, so all methods see
exactly the same occlusion pattern.
"""
import argparse
import csv
import os
import pickle
import re
import sys
from typing import Dict, List

import numpy as np
from tqdm import tqdm

# Make this script runnable from project root or from tools/.
_THIS_DIR = os.path.dirname(os.path.abspath(__file__))
if _THIS_DIR not in sys.path:
    sys.path.insert(0, _THIS_DIR)

from tools.gen_range_av2 import (  # noqa: E402
    py_top3_farthest_mean,
    project_ry_maxz,
    project_rp_density,
    read_points_xyz,
)
from tools.utils_av2 import check_dir, check_path, load_config  # noqa: E402


DEFAULT_OCC_DEGREES = [30, 60, 90, 120]


def wrap_pi(a: np.ndarray) -> np.ndarray:
    return (a + np.pi) % (2.0 * np.pi) - np.pi


def apply_yaw_occlusion(points_xyz: np.ndarray, center_yaw_rad: float, occ_degree: float) -> np.ndarray:
    """Remove points whose horizontal yaw angle falls inside the occlusion sector."""
    if points_xyz.size == 0:
        return points_xyz
    yaw = np.arctan2(points_xyz[:, 1], points_xyz[:, 0])
    half_width = np.deg2rad(float(occ_degree)) / 2.0
    diff = np.abs(wrap_pi(yaw - float(center_yaw_rad)))
    keep_mask = diff > half_width
    return points_xyz[keep_mask]


def auto_discover_test_splits(cache_root: str, info_path: str, include_all: bool = False) -> List[Dict]:
    """
    Discover AV2 test splits generated by gen_index_av2.py.

    Default behavior is aimed at the user's three-test-set setup: if city/test split
    files exist, the global ALL split is skipped. Pass --include_all to include it.
    """
    splits = []
    pat = re.compile(r'^av2_test_([a-z0-9]+)_db\.npy$')
    city_splits = []
    for fn in sorted(os.listdir(cache_root)):
        m = pat.match(fn)
        if not m:
            continue
        ctag = m.group(1)
        dbp = os.path.join(cache_root, fn)
        qp = os.path.join(cache_root, f'av2_test_{ctag}_query.npy')
        if os.path.exists(qp):
            city_splits.append({
                'name': f'AV2_TEST_{ctag.upper()}',
                'database_path': dbp,
                'query_path': qp,
                'info_path': info_path,
                'city_tag': ctag.upper(),
            })

    all_db = os.path.join(cache_root, 'av2_test_db.npy')
    all_q = os.path.join(cache_root, 'av2_test_query.npy')
    all_split = []
    if os.path.exists(all_db) and os.path.exists(all_q):
        all_split.append({
            'name': 'AV2_TEST_ALL',
            'database_path': all_db,
            'query_path': all_q,
            'info_path': info_path,
            'city_tag': 'ALL',
        })

    if city_splits:
        splits.extend(city_splits)
        if include_all:
            splits = all_split + splits
    else:
        splits.extend(all_split)

    return splits


def filter_splits_by_tags(splits: List[Dict], city_tags: str) -> List[Dict]:
    if not city_tags:
        return splits
    wanted = {x.strip().upper() for x in city_tags.split(',') if x.strip()}
    if not wanted:
        return splits
    return [s for s in splits if s['city_tag'].upper() in wanted or s['name'].upper() in wanted]


def collect_unique_query_indices(splits: List[Dict]) -> np.ndarray:
    ids = []
    for sp in splits:
        arr = np.load(sp['query_path'])
        if arr.size == 0:
            continue
        ids.extend(arr[:, 0].astype(np.int64).tolist())
    if not ids:
        return np.empty((0,), dtype=np.int64)
    return np.array(sorted(set(ids)), dtype=np.int64)


def build_or_load_centers(query_indices: np.ndarray, infos: List[Dict], seed: int, config_csv: str,
                          overwrite: bool = False) -> Dict[int, float]:
    centers = {}
    if os.path.exists(config_csv) and not overwrite:
        with open(config_csv, 'r', newline='') as f:
            reader = csv.DictReader(f)
            for row in reader:
                centers[int(row['frame_index'])] = float(row['center_yaw_rad'])
        missing = [int(i) for i in query_indices if int(i) not in centers]
        if not missing:
            return centers
        print(f'[WARN] center config exists but misses {len(missing)} frames; generating missing centers.')

    rng = np.random.default_rng(int(seed))
    for idx in query_indices:
        idx = int(idx)
        if idx not in centers or overwrite:
            centers[idx] = float(rng.uniform(-np.pi, np.pi))

    check_dir(os.path.dirname(config_csv))
    with open(config_csv, 'w', newline='') as f:
        fieldnames = ['frame_index', 'timestamp', 'log_id', 'lidar_filename', 'center_yaw_rad', 'center_yaw_deg', 'seed']
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        for idx in query_indices:
            idx = int(idx)
            info = infos[idx]
            fname = info['lidar_infos']['LIDAR_TOP']['filename']
            center = centers[idx]
            writer.writerow({
                'frame_index': idx,
                'timestamp': int(info.get('timestamp', info['lidar_infos']['LIDAR_TOP'].get('timestamp', -1))),
                'log_id': info.get('log_id', info.get('scene_token', '')),
                'lidar_filename': fname,
                'center_yaw_rad': f'{center:.12f}',
                'center_yaw_deg': f'{np.rad2deg(center):.6f}',
                'seed': int(seed),
            })
    return centers


def save_range_npz(points: np.ndarray, out_path: str,
                   proj_H: int, proj_W: int, proj_R: int, max_radius: float,
                   pitch_mode: str, pitch_percentiles):
    # Robust guard: external disks / fresh output roots may not have the per-degree
    # folder created yet. Creating it here makes the save step safe even if the
    # caller forgets to create the folder or the script is resumed midway.
    out_dir = os.path.dirname(out_path)
    if out_dir:
        os.makedirs(out_dir, exist_ok=True)

    py, pitch_minmax = py_top3_farthest_mean(
        points, proj_H=proj_H, proj_W=proj_W, max_radius=max_radius,
        pitch_mode=pitch_mode, pitch_percentiles=pitch_percentiles
    )
    ry = project_ry_maxz(points, proj_R=proj_R, proj_W=proj_W, max_range_xy=max_radius)
    rp = project_rp_density(points, proj_R=proj_R, proj_H=proj_H,
                            pitch_minmax=pitch_minmax, max_range_3d=max_radius)
    np.savez_compressed(
        out_path,
        py=py.astype(np.float32),
        ry=ry.astype(np.float32),
        rp=rp.astype(np.float32),
        pitch_min=np.float32(pitch_minmax[0]),
        pitch_max=np.float32(pitch_minmax[1]),
    )


def generate_occ_ranges(dataroot: str,
                        infos: List[Dict],
                        query_indices: np.ndarray,
                        centers: Dict[int, float],
                        out_root: str,
                        occ_degrees: List[int],
                        seed: int,
                        overwrite: bool,
                        proj_H: int,
                        proj_W: int,
                        proj_R: int,
                        max_radius: float,
                        pitch_mode: str,
                        pitch_percentiles):
    for deg in occ_degrees:
        folder = os.path.join(out_root, f'occ_{int(deg):03d}_seed{int(seed)}')
        check_dir(folder)
        log_csv = os.path.join(out_root, 'occ_configs', f'occ_{int(deg):03d}_seed{int(seed)}_frames.csv')
        check_dir(os.path.dirname(log_csv))

        rows = []
        pbar = tqdm(query_indices, desc=f'gen query LiDAR OCC-{int(deg)}', ncols=100)
        for idx in pbar:
            idx = int(idx)
            info = infos[idx]
            fname = info['lidar_infos']['LIDAR_TOP']['filename']
            pcl_path = os.path.join(dataroot, fname)
            out_name = os.path.splitext(os.path.basename(fname))[0] + '.npz'
            dst_path = os.path.join(folder, out_name)
            if os.path.exists(dst_path) and not overwrite:
                continue

            points = read_points_xyz(pcl_path)
            d = np.linalg.norm(points, axis=1)
            points = points[d > 2.0]
            n_before = int(points.shape[0])
            points_occ = apply_yaw_occlusion(points, centers[idx], float(deg))
            n_after = int(points_occ.shape[0])
            removed_ratio = 0.0 if n_before == 0 else (n_before - n_after) / float(n_before)

            save_range_npz(points_occ, dst_path, proj_H, proj_W, proj_R, max_radius, pitch_mode, pitch_percentiles)
            rows.append({
                'frame_index': idx,
                'timestamp': int(info.get('timestamp', info['lidar_infos']['LIDAR_TOP'].get('timestamp', -1))),
                'log_id': info.get('log_id', info.get('scene_token', '')),
                'lidar_filename': fname,
                'out_npz': dst_path,
                'occ_degree': int(deg),
                'center_yaw_rad': f'{centers[idx]:.12f}',
                'center_yaw_deg': f'{np.rad2deg(centers[idx]):.6f}',
                'points_before': n_before,
                'points_after': n_after,
                'removed_ratio': f'{removed_ratio:.8f}',
                'seed': int(seed),
            })

        # Keep a per-degree log. If files were skipped, the log records only newly generated frames.
        if rows or overwrite or not os.path.exists(log_csv):
            with open(log_csv, 'w', newline='') as f:
                fieldnames = [
                    'frame_index', 'timestamp', 'log_id', 'lidar_filename', 'out_npz',
                    'occ_degree', 'center_yaw_rad', 'center_yaw_deg',
                    'points_before', 'points_after', 'removed_ratio', 'seed'
                ]
                writer = csv.DictWriter(f, fieldnames=fieldnames)
                writer.writeheader()
                for r in rows:
                    writer.writerow(r)
        print(f'[OCC-{int(deg)}] saved query range folder: {folder}')


def parse_args():
    ap = argparse.ArgumentParser(description='Generate AV2S query-only LiDAR occlusion range npz files.')
    ap.add_argument('--config', default='config/config_av2.yaml')
    ap.add_argument('--dataroot', default=None, help='Override cfg[data][data_root_dir]')
    ap.add_argument('--cache_root', default=None, help='Override dirname of cfg[data][database_path]')
    ap.add_argument('--info_path', default=None, help='Override cfg[data][test_info_path]')
    ap.add_argument('--out_root', default=None, help='Default: <cache_root>/RANGE_DOME3VIEW_OCC')
    ap.add_argument('--occ_degrees', type=int, nargs='+', default=DEFAULT_OCC_DEGREES)
    ap.add_argument('--seed', type=int, default=2026)
    ap.add_argument('--city_tags', default='', help='Comma separated tags, e.g. MIA,PIT. Default: all discovered test splits.')
    ap.add_argument('--include_all', action='store_true', help='Also include AV2_TEST_ALL when city/test splits exist.')
    ap.add_argument('--overwrite', action='store_true')
    ap.add_argument('--proj_H', type=int, default=32)
    ap.add_argument('--proj_W', type=int, default=768)
    ap.add_argument('--proj_R', type=int, default=64)
    ap.add_argument('--max_radius', type=float, default=80.0)
    ap.add_argument('--pitch_mode', default='minmax', choices=['minmax', 'percentile'])
    ap.add_argument('--pitch_percentiles', type=float, nargs=2, default=(1.0, 99.0))
    return ap.parse_args()


def main():
    args = parse_args()
    cfg = load_config(args.config)

    dataroot = args.dataroot or cfg['data']['data_root_dir']
    cache_root = args.cache_root or os.path.dirname(cfg['data']['database_path'])
    info_path = args.info_path or cfg['data'].get('test_info_path', os.path.join(cache_root, 'av2_infos_test.pkl'))
    out_root = args.out_root or os.path.join(cache_root, 'RANGE_DOME3VIEW_OCC')
    check_path(dataroot, cache_root, info_path)
    check_dir(out_root, os.path.join(out_root, 'occ_configs'))

    splits = auto_discover_test_splits(cache_root, info_path, include_all=args.include_all)
    splits = filter_splits_by_tags(splits, args.city_tags)
    if not splits:
        raise FileNotFoundError(f'No AV2 test split query files found in {cache_root}')
    print('[splits]')
    for s in splits:
        print(f"  {s['name']}: query={s['query_path']}")

    with open(info_path, 'rb') as f:
        infos = pickle.load(f)

    query_indices = collect_unique_query_indices(splits)
    if query_indices.size == 0:
        raise RuntimeError('No query frame indices found in the selected splits.')
    print(f'[query frames] unique query frames = {len(query_indices)}')

    center_csv = os.path.join(out_root, 'occ_configs', f'fixed_query_yaw_centers_seed{int(args.seed)}.csv')
    centers = build_or_load_centers(query_indices, infos, int(args.seed), center_csv, overwrite=args.overwrite)
    print(f'[center config] {center_csv}')

    generate_occ_ranges(
        dataroot=dataroot,
        infos=infos,
        query_indices=query_indices,
        centers=centers,
        out_root=out_root,
        occ_degrees=list(args.occ_degrees),
        seed=int(args.seed),
        overwrite=bool(args.overwrite),
        proj_H=int(args.proj_H),
        proj_W=int(args.proj_W),
        proj_R=int(args.proj_R),
        max_radius=float(args.max_radius),
        pitch_mode=args.pitch_mode,
        pitch_percentiles=tuple(args.pitch_percentiles),
    )
    print('[done] Query-only occluded range npz generation finished.')


if __name__ == '__main__':
    main()
